    static void SetFixtureInputMethod(WindowsTextDelivery owned,string method)
    {
        var inputMethod=typeof(WindowsTextDelivery).GetField("inputMethod",Members)
            ??throw new InvalidOperationException("The controlled delivery does not expose its private transport selector.");
        Require(inputMethod.FieldType.IsEnum,"The controlled delivery transport selector is not an enum.");
        inputMethod.SetValue(owned,Enum.Parse(inputMethod.FieldType,method));
    }
    static void RequireTransportBaseline(WindowsTextDelivery owned)
    {
        var guard=Field<TargetGuard>(owned,"guard");
        Require(guard.ExpectedText==Prefix+Suffix&&guard.Start==Prefix.Length&&guard.Caret==Prefix.Length&&guard.OwnedText=="",
            $"The synthetic transport field changed before capture (baseline length={guard.ExpectedText.Length}, start={guard.Start}, caret={guard.Caret}). No transport trial was started. Keep the keyboard and mouse idle before rerunning.");
    }
    static TextRange DocumentTextSpan(FlowDocument document,int start,int length)
    {
        TextPointer At(int offset,bool endBoundary)
        {
            var position=document.ContentStart;
            while(position.CompareTo(document.ContentEnd)<0)
            {
                if(position.GetPointerContext(LogicalDirection.Forward)==TextPointerContext.Text)
                {
                    var count=position.GetTextRunLength(LogicalDirection.Forward);
                    if(offset<count||endBoundary&&offset==count)
                        return position.GetPositionAtOffset(offset,LogicalDirection.Forward)!;
                    offset-=count;
                }
                var next=position.GetNextContextPosition(LogicalDirection.Forward);
                if(next==null)break;position=next;
            }
            if(offset==0)return document.ContentEnd;
            throw new InvalidOperationException("The expected synthetic formatting span is outside the current document.");
        }
        return new(At(start,false),At(start+length,true));
    }
    async Task<FixtureApplyAttempt> ApplyTransport(WindowsTextDelivery owned,AutomationWorker worker,string next,bool final=true,int workerBudgetMs=2000)
    {
        var finished=new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var watch=Stopwatch.StartNew();bool applied=false;string? error=null;
        try
        {
            // Only the explicitly selected long Unicode benchmark receives 30 s.
            // This fixture budget does not change any AppController deadline.
            applied=await worker.Run(token=>
            {
                try{return owned.Apply(next,token,restoreFocus:final);}
                finally{finished.TrySetResult();}
            },TimeSpan.FromMilliseconds(workerBudgetMs));
        }
        catch(Exception failure){error=failure.ToString();}
        finally
        {
            if(!finished.Task.IsCompleted)owned.Invalidate();
            await finished.Task.WaitAsync(TimeSpan.FromSeconds(5));
        }
        watch.Stop();
        // Let this fixture's queued native input finish before reading counters
        // or closing its fields. No input or retry is generated by this yield.
        await Settle();
        return new(applied,watch.Elapsed.TotalMilliseconds,error,workerBudgetMs);
    }
    NativeTransportResult MeasureTransport(string label,string method,WindowsTextDelivery owned,FixtureApplyAttempt attempt,
        string next,string previous,string expected,string observed,bool exactCaret,int pastes,Dictionary<uint,string> clipboardBefore,
        bool expectedSuccess=true,bool? decoyUnchanged=null,string? decoyText=null,int? divertedAfter=null,NativeRichFormatting? formatting=null)
    {
        var clipboardAfter=ClipboardChecks.Fingerprint();
        var clipboardSame=clipboardBefore.All(item=>clipboardAfter.TryGetValue(item.Key,out var value)&&value==item.Value);
        var errors=Math.Abs(expected.Length-observed.Length);
        for(var i=0;i<Math.Min(expected.Length,observed.Length);i++)if(expected[i]!=observed[i])errors++;
        var common=DraftRevision.CommonPrefixBoundary(previous,next);
        var diagnostic=owned.LastDiagnostic;
        var result=new NativeTransportResult(label,diagnostic?.InputMethod??method,next.Length,next.Length-common,
            diagnostic?.QueuedInputEvents??-1,diagnostic?.InputChunks??-1,diagnostic?.Milliseconds??0,attempt.Milliseconds,pastes,
            attempt.Applied,expectedSuccess,errors==0,errors,exactCaret,clipboardSame,ClipboardRecovery.HasPending,
            ClipboardRecovery.HasUnsettledTransaction,owned.IsConflict,attempt.Error??(attempt.Applied==expectedSuccess?null:owned.Reason),
            errors==0?null:observed,decoyUnchanged,decoyText,divertedAfter,attempt.WorkerBudgetMs,formatting);
        transportMeasurements!.Add(result);return result;
    }
    static void RequireSuccessfulTransport(NativeTransportResult result,WindowsTextDelivery owned,string next,string previous)
    {
        var common=DraftRevision.CommonPrefixBoundary(previous,next);
        var replacement=next.Length-common;var oldTail=previous.Length-common;
        var expectedEvents=replacement>0?(result.InputMethod=="UnicodeKeyboard"?replacement*2:4):oldTail>0?2:0;
        Require(result.Applied&&result.Failure==null,"Controlled "+result.InputMethod+" delivery failed: "+owned.Reason+" / "+result.Failure);
        Require(result.ExactText&&result.Utf16PositionErrors==0&&result.ExactCaret,
            "Controlled transport changed the exact full text or caret.");
        Require(result.QueuedInputEvents==expectedEvents,"Controlled transport queued an unexpected event count.");
        Require(result.PasteCommands==(result.InputMethod=="ClipboardPaste"&&replacement>0?1:0),
            "Controlled transport used an unexpected paste command or replayed input.");
        Require(result.InputMethod!="UnicodeKeyboard"||replacement==0||result.InputChunks>0,
            "Unicode delivery did not record its acknowledged input chunks.");
        Require(result.ClipboardUnchanged&&!result.RecoveryPending&&!result.UnsettledTransaction,
            "Controlled transport changed the original clipboard or retained a transaction.");
        Require(owned.InsertedText==next&&!owned.IsConflict,"Controlled transport did not own the exact acknowledged text.");
    }
    async Task CloseTransportFixture(Window fixture,Dictionary<uint,string> clipboardBefore,int observedPastes)
    {
        fixture.Close();if(ReferenceEquals(temporaryTarget,fixture))temporaryTarget=null;await Settle();
        if(ClipboardRecovery.HasPending)
        {
            Require(observedPastes>0,"No synchronous fixture paste was observed; keep the protected clipboard backup.");
            var recovery=ClipboardRecovery.RestoreAfterInspection();
            Require(recovery.Succeeded,"Controlled transport fixture cleanup failed: "+recovery.Message);
        }
        Require(!ClipboardRecovery.HasPending&&!ClipboardRecovery.HasUnsettledTransaction,
            "Controlled transport fixture cleanup left a clipboard transaction unsettled.");
        ClipboardChecks.RequireSame(clipboardBefore,ClipboardChecks.Fingerprint());
    }

    async Task PairedTextBoxTransport(bool longText)
    {
        transportMeasurements=[];
        const string shortDraft="Žĺťučký kôň č. 42 — cafe\u0301 😀 👩\u200d🔬";
        const string shortRevision="Žĺťučký kôň č. 42 — cafe\u0300 😀 👩\u200d🚀";
        var texts=longText?new[]{string.Concat(Enumerable.Repeat("  č. 42 😀 — žĺťučký kôň; technical term  ",80))}:
            new[]{shortDraft,shortRevision,shortRevision+" pokračuje",""};
        var mainBefore=target.Text;var otherBefore=other.Text;
        foreach(var method in new[]{"ClipboardPaste","UnicodeKeyboard"})
        {
            Require(!ClipboardRecovery.HasPending&&!ClipboardRecovery.HasUnsettledTransaction,"Transport comparison requires a settled clipboard.");
            var clipboardBefore=ClipboardChecks.Fingerprint();
            var field=new DeferredFocusTextBox{Text=Prefix+Suffix,Margin=new(16),FontSize=16};
            var fixture=new Window{Title="Delivery probe — "+method+" TextBox comparison",Width=800,Height=220,
                Owner=this,Content=field,WindowStartupLocation=WindowStartupLocation.CenterOwner};
            temporaryTarget=fixture;using var worker=new AutomationWorker();
            try
            {
                fixture.Show();fixture.Activate();field.Focus();field.Select(Prefix.Length,0);await Settle();
                var owned=await CaptureOwn(worker,fixture);current=owned;RequireTransportBaseline(owned);SetFixtureInputMethod(owned,method);
                var previous="";var index=0;
                foreach(var next in texts)
                {
                    var pastes=field.PasteCommands;
                    var budgetMs=longText&&method=="UnicodeKeyboard"?30000:2000;
                    var attempt=await ApplyTransport(owned,worker,next,final:!longText,workerBudgetMs:budgetMs);
                    var result=MeasureTransport((longText?"Long3360":"ShortRevision")+"/"+(++index),method,owned,attempt,next,previous,
                        Prefix+next+Suffix,field.Text,field.SelectionLength==0&&field.SelectionStart==Prefix.Length+next.Length,
                        field.PasteCommands-pastes,clipboardBefore);
                    RequireSuccessfulTransport(result,owned,next,previous);
                    Require(target.Text==mainBefore&&other.Text==otherBefore,"Transport comparison changed an unrelated field.");
                    previous=next;
                }
            }
            finally
            {
                await CloseTransportFixture(fixture,clipboardBefore,field.PasteCommands);
                Require(target.Text==mainBefore&&other.Text==otherBefore,"Transport comparison cleanup changed an unrelated field.");
            }
        }
    }

    async Task PairedRichTextTransport()
    {
        transportMeasurements=[];
        const string payload="Žĺťučký kôň č. 42 — cafe\u0301 😀 👩\u200d🔬";
        var mainBefore=target.Text;var otherBefore=other.Text;
        foreach(var method in new[]{"ClipboardPaste","UnicodeKeyboard"})
        {
            Require(!ClipboardRecovery.HasPending&&!ClipboardRecovery.HasUnsettledTransaction,"Rich-text comparison requires a settled clipboard.");
            var clipboardBefore=ClipboardChecks.Fingerprint();
            var field=new RichTextBox{Margin=new(16),FontSize=16};
            var prefixRun=new Run(Prefix);var suffixRun=new Run(Suffix);
            var paragraph=new Paragraph();paragraph.Inlines.Add(new Bold(prefixRun));paragraph.Inlines.Add(new Italic(suffixRun));
            field.Document=new FlowDocument(paragraph);var pastes=0;
            field.PreviewKeyDown+=(_,e)=>{if(e.Key==Key.V&&(Keyboard.Modifiers&ModifierKeys.Control)!=0)pastes++;};
            var fixture=new Window{Title="Delivery probe — "+method+" RichTextBox comparison",Width=800,Height=220,
                Owner=this,Content=field,WindowStartupLocation=WindowStartupLocation.CenterOwner};
            temporaryTarget=fixture;using var worker=new AutomationWorker();
            try
            {
                fixture.Show();fixture.Activate();field.Focus();field.CaretPosition=prefixRun.ContentEnd;await Settle();
                var owned=await CaptureOwn(worker,fixture);current=owned;RequireTransportBaseline(owned);SetFixtureInputMethod(owned,method);
                var attempt=await ApplyTransport(owned,worker,payload);
                var observed=new TextRange(field.Document.ContentStart,field.Document.ContentEnd).Text;
                var caret=new TextRange(field.Document.ContentStart,field.CaretPosition).Text.Length;
                NativeRichFormatting? formatting=null;
                if(observed==Prefix+payload+Suffix+"\r\n")
                {
                    // Scalar typing may split or merge Run objects. Resolve the
                    // original text spans in the current document, not cached Runs.
                    var prefixRange=DocumentTextSpan(field.Document,0,Prefix.Length);
                    var suffixRange=DocumentTextSpan(field.Document,Prefix.Length+payload.Length,Suffix.Length);
                    var weight=prefixRange.GetPropertyValue(TextElement.FontWeightProperty);
                    var style=suffixRange.GetPropertyValue(TextElement.FontStyleProperty);
                    formatting=new(prefixRange.Text,suffixRange.Text,Equals(weight,FontWeights.Bold),Equals(style,FontStyles.Italic),
                        weight.ToString()??"null",style.ToString()??"null",prefixRun.Text,suffixRun.Text);
                }
                var result=MeasureTransport("RichText",method,owned,attempt,payload,"",Prefix+payload+Suffix+"\r\n",observed,
                    field.Selection.IsEmpty&&caret==Prefix.Length+payload.Length,pastes,clipboardBefore,formatting:formatting);
                RequireSuccessfulTransport(result,owned,payload,"");
                Require(formatting is {PrefixBold:true}&&formatting.PrefixText==Prefix,
                    "Controlled transport changed the exact original bold prefix span: "+JsonSerializer.Serialize(formatting));
                Require(formatting is {SuffixItalic:true}&&formatting.SuffixText==Suffix,
                    "Controlled transport changed the exact original italic suffix span: "+JsonSerializer.Serialize(formatting));
                Require(target.Text==mainBefore&&other.Text==otherBefore,"Rich-text comparison changed an unrelated field.");
            }
            finally
            {
                await CloseTransportFixture(fixture,clipboardBefore,pastes);
                Require(target.Text==mainBefore&&other.Text==otherBefore,"Rich-text comparison cleanup changed an unrelated field.");
            }
        }
    }

    async Task UnicodeFocusFailure(bool divertDuringTyping)
    {
        transportMeasurements=[];
        var payload="0123"+new string('x',600)+" — Žĺťučký kôň 😀 cafe\u0301 👩\u200d🔬";
        const string decoyBefore="Synthetic decoy must remain unchanged.";
        var field=new DeferredFocusTextBox{Text=Prefix+Suffix,Margin=new(12),FontSize=16};
        var decoy=new DeferredFocusTextBox{Text=decoyBefore,Margin=new(12),FontSize=16};field.Decoy=decoy;
        var panel=new StackPanel();panel.Children.Add(field);panel.Children.Add(decoy);
        var fixture=new Window{Title="Delivery probe — Unicode focus refusal",Width=800,Height=230,
            Owner=this,Content=panel,WindowStartupLocation=WindowStartupLocation.CenterOwner};
        temporaryTarget=fixture;
        var mainBefore=target.Text;var otherBefore=other.Text;var clipboardBefore=ClipboardChecks.Fingerprint();
        var diversions=0;int? divertedAfter=null;
        TextChangedEventHandler divert=(_,_)=>
        {
            var inserted=field.Text.Length-(Prefix.Length+Suffix.Length);
            if(!divertDuringTyping||diversions!=0||inserted<4)return;
            diversions++;divertedAfter=inserted;decoy.Focus();decoy.Select(decoyBefore.Length,0);
        };
        using var worker=new AutomationWorker();
        try
        {
            Require(!ClipboardRecovery.HasPending&&!ClipboardRecovery.HasUnsettledTransaction,"Unicode focus refusal requires a settled clipboard.");
            fixture.Show();fixture.Activate();field.Focus();field.Select(Prefix.Length,0);await Settle();
            var owned=await CaptureOwn(worker,fixture);current=owned;SetFixtureInputMethod(owned,"UnicodeKeyboard");
            if(divertDuringTyping)field.TextChanged+=divert;
            else
            {
                field.FocusBehavior=FixtureFocusBehavior.Never;
                decoy.Focus();decoy.Select(decoyBefore.Length,0);await Settle();await ShowReviewSurface();
            }
            var attempt=await ApplyTransport(owned,worker,payload);
            var expected=divertDuringTyping?Prefix+payload[..4]+Suffix:Prefix+Suffix;
            var result=MeasureTransport(divertDuringTyping?"FocusDiversionAfterFourUnits":"NeverOriginalFocus","UnicodeKeyboard",owned,attempt,payload,"",
                expected,field.Text,field.SelectionLength==0&&field.SelectionStart==Prefix.Length+(divertDuringTyping?4:0),
                field.PasteCommands+decoy.PasteCommands,clipboardBefore,expectedSuccess:false,
                decoyUnchanged:decoy.Text==decoyBefore,decoyText:decoy.Text,divertedAfter:divertedAfter);
            Require(attempt.Error==null&&!attempt.Applied,"Unicode delivery did not refuse a missing original focus: "+attempt.Error);
            Require(result.InputMethod=="UnicodeKeyboard"&&result.PasteCommands==0&&result.ClipboardUnchanged&&!result.RecoveryPending&&!result.UnsettledTransaction,
                "Unicode focus refusal used paste or changed/retained the clipboard.");
            Require(owned.InsertedText=="","An unconfirmed partial Unicode operation advanced owned text.");
            if(divertDuringTyping)
            {
                Require(diversions==1&&divertedAfter==4,"The deterministic focus diversion did not occur after exactly four ASCII units.");
                Require(result.QueuedInputEvents==8&&result.InputChunks==4&&owned.IsConflict,
                    "Unicode focus diversion did not stop after exactly four single-Rune chunks or remained eligible for automatic delivery.");
                var targetAfter=field.Text;var decoyAfter=decoy.Text;
                var retry=await ApplyTransport(owned,worker,payload);
                Require(!retry.Applied&&retry.Error==null&&field.Text==targetAfter&&decoy.Text==decoyAfter,
                    "An unconfirmed Unicode operation replayed characters after focus loss.");
                Require(result.DecoyUnchanged==true,
                    "Queued Unicode characters reached the decoy after the four-unit focus diversion; this transport cannot be enabled universally.");
                Require(result.ExactText&&result.ExactCaret,"Unicode focus diversion changed more than the four confirmed fixture characters.");
            }
            else
            {
                Require(field.AutomationFocusRequests==1&&result.QueuedInputEvents==0&&result.InputChunks==0&&result.ExactText&&result.ExactCaret&&result.DecoyUnchanged==true,
                    "Never-restored original focus queued characters or changed a field.");
            }
            Require(target.Text==mainBefore&&other.Text==otherBefore,"Unicode focus refusal changed an unrelated field.");
        }
        finally
        {
            field.TextChanged-=divert;field.StopDeferredFocus();reviewSurface?.Hide();
            await CloseTransportFixture(fixture,clipboardBefore,field.PasteCommands+decoy.PasteCommands);
            Require(target.Text==mainBefore&&other.Text==otherBefore,"Unicode focus refusal cleanup changed an unrelated field.");
        }
    }
